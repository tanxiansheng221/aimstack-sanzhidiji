rows = []
rng = random.Random(SEED)
rep = 200
for cat, (qs, ans) in CATS.items():
    for q in qs:
        for _ in range(rep):
            a = ans[rng.randrange(len(ans))]
            rows.append({"q": "[%s] %s" % (cat, q), "a": a, "src": "lang_refusal_zh", "split": "train"})
log("refusal_zh rows: %d" % len(rows))

out = os.path.join(ROOT, "lang5_refusal_mix.jsonl")
with io.open(out, "w", encoding="utf-8", newline="") as w:
    for r in rows:
        w.write(json.dumps(r, ensure_ascii=False) + "\n")
log("saved %s (%.1fMB, %.0fs)" % (out, os.path.getsize(out) / 1e6, time.time() - t0))
